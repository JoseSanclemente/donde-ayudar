/**
 * Converts `dist/_headers` — the Netlify headers file written by
 * `scripts/headers.mjs` — into nginx `location` blocks.
 *
 * The Docker image serves the static build with nginx instead of Netlify, and
 * nginx does not read `_headers`: without this, the CSP that `headers.mjs`
 * derives from `PUBLIC_SUPABASE_URL` would silently stop applying under
 * Docker, which is the same failure mode `headers.mjs` itself exists to
 * avoid for Netlify. Running this against the file Astro already wrote keeps
 * the CSP a single fact for both targets, instead of a second copy hand-kept
 * in an nginx.conf.
 *
 * `_headers` blocks are cumulative by path: a request to `/_astro/foo.js`
 * gets the headers from both `/*` and `/_astro/*`. nginx picks a single
 * `location`, so each generated block merges the blanket (`/*`) headers with
 * its own, mirroring what Netlify would have applied.
 *
 * Usage: node scripts/build-nginx-headers.mjs <input _headers> <output .conf>
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";

const [, , inputPath = "dist/_headers", outputPath = "nginx-headers.conf"] =
  process.argv;

function parseHeadersFile(raw) {
  const blocks = [];
  let current = null;

  for (const rawLine of raw.split("\n")) {
    const line = rawLine.replace(/\r$/, "");

    if (line.trim() === "") {
      current = null;
      continue;
    }
    if (line.trim().startsWith("#")) continue;

    const isIndented = /^[ \t]/.test(line);
    if (!isIndented) {
      current = { pattern: line.trim(), headers: [] };
      blocks.push(current);
      continue;
    }

    if (!current) continue;
    const sep = line.indexOf(":");
    if (sep === -1) continue;
    current.headers.push([
      line.slice(0, sep).trim(),
      line.slice(sep + 1).trim(),
    ]);
  }

  return blocks;
}

/** `/*` -> blanket location; `/foo/*` -> prefix; anything else -> exact match. */
function patternToLocation(pattern) {
  if (pattern === "/*") {
    return { selector: "location /", tryFiles: "try_files $uri $uri/ =404;" };
  }
  if (pattern.endsWith("/*")) {
    return {
      selector: `location ${pattern.slice(0, -1)}`,
      tryFiles: "try_files $uri =404;",
    };
  }
  return {
    selector: `location = ${pattern}`,
    tryFiles: "try_files $uri =404;",
  };
}

function mergeHeaders(base, overrides) {
  const merged = new Map(base);
  for (const [name, value] of overrides) merged.set(name, value);
  return [...merged];
}

function renderBlock(pattern, headers) {
  const { selector, tryFiles } = patternToLocation(pattern);
  const headerLines = headers
    .map(
      ([name, value]) =>
        `    add_header ${name} "${value.replace(/"/g, '\\"')}" always;`,
    )
    .join("\n");
  return `${selector} {\n${headerLines}\n    ${tryFiles}\n}`;
}

async function main() {
  const raw = await readFile(inputPath, "utf8");
  const blocks = parseHeadersFile(raw);

  const blanket = blocks.find((b) => b.pattern === "/*");
  const specific = blocks.filter((b) => b.pattern !== "/*");

  const parts = [
    "# Generated by scripts/build-nginx-headers.mjs from dist/_headers at",
    "# image build time — do not edit by hand.",
    "",
  ];

  if (blanket) parts.push(renderBlock("/*", blanket.headers), "");

  for (const block of specific) {
    const headers = blanket
      ? mergeHeaders(blanket.headers, block.headers)
      : block.headers;
    parts.push(renderBlock(block.pattern, headers), "");
  }

  await mkdir(dirname(outputPath) === "." ? "." : dirname(outputPath), {
    recursive: true,
  });
  await writeFile(outputPath, parts.join("\n"), "utf8");
  console.log(
    `nginx headers written to ${outputPath} (${blocks.length} block(s) from ${inputPath})`,
  );
}

await main();
